CREATE TABLE IF NOT EXISTS bilties_jamshedpur (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id TEXT NOT NULL REFERENCES trips_jamshedpur(id) ON DELETE CASCADE,
  bilty_number TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (trip_id, bilty_number)
);

CREATE TABLE IF NOT EXISTS bilties_maharashtra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id TEXT NOT NULL REFERENCES trips_maharashtra(id) ON DELETE CASCADE,
  bilty_number TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending',
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (trip_id, bilty_number)
);

CREATE INDEX IF NOT EXISTS idx_bilties_jamshedpur_trip_id ON bilties_jamshedpur(trip_id);
CREATE INDEX IF NOT EXISTS idx_bilties_maharashtra_trip_id ON bilties_maharashtra(trip_id);
